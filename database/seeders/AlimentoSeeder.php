use App\Services\FoodNameNormalizerService;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;

class AlimentoSeeder extends Seeder
{
    public function run(): void
    {
        $alimentos = $this->obtenerCatalogoAlimentos();

        DB::transaction(function () use ($alimentos) {
            foreach ($alimentos as $item) {
                $alimento = Alimento::updateOrCreate(
                    [
                        'nom_ali' => $item['nom_ali'],
                    ],
                    [
                        'nom_ext_ali' => $item['nom_ext_ali'] ?? $item['nom_ali'],
                        'tip_ali' => $item['tip_ali'] ?? 'alimento',
                        'des_ali' => $item['des_ali'] ?? null,
                        'mar_ali' => $item['mar_ali'] ?? null,
                        'src_ali' => $item['src_ali'] ?? 'manual',
                        'ref_ext_ali' => $item['ref_ext_ali'] ?? null,
                        'idi_ali' => 'es',
                        'pai_ali' => $item['pai_ali'] ?? 'GL',
                        'est_ali' => Alimento::ESTADO_ACTIVO,
                    ]
                );

                if (isset($item['nutricion'])) {
                    $nut = $item['nutricion'];

                    // Archivar composiciones vigentes anteriores diferentes si hubiera
                    TablaComposicionNutricional::where('cod_alimentos_tcn', $alimento->cod_alimentos)
                        ->where('est_tcn', TablaComposicionNutricional::ESTADO_VIGENTE)
                        ->update(['est_tcn' => TablaComposicionNutricional::ESTADO_ARCHIVADA]);

                    TablaComposicionNutricional::updateOrCreate(
                        [
                            'cod_alimentos_tcn' => $alimento->cod_alimentos,
                            'fec_tcn' => now()->toDateString(),
                        ],
                        [
                            'por_ref_tcn' => $nut['por_ref_tcn'] ?? '100 g',
                            'cant_ref_tcn' => $nut['cant_ref_tcn'] ?? 100.0,
                            'uni_ref_tcn' => $nut['uni_ref_tcn'] ?? 'gramos',
                            'cal_tcn' => $nut['cal_tcn'] ?? 0.0,
                            'pro_tcn' => $nut['pro_tcn'] ?? 0.0,
                            'gra_tcn' => $nut['gra_tcn'] ?? 0.0,
                            'car_tcn' => $nut['car_tcn'] ?? 0.0,
                            'fib_tcn' => $nut['fib_tcn'] ?? 0.0,
                            'azu_tcn' => $nut['azu_tcn'] ?? 0.0,
                            'gra_sat_tcn' => $nut['gra_sat_tcn'] ?? 0.0,
                            'gra_mono_tcn' => $nut['gra_mono_tcn'] ?? 0.0,
                            'gra_poli_tcn' => $nut['gra_poli_tcn'] ?? 0.0,
                            'sod_tcn' => $nut['sod_tcn'] ?? 0.0,
                            'pot_tcn' => $nut['pot_tcn'] ?? 0.0,
                            'col_tcn' => $nut['col_tcn'] ?? 0.0,
                            'calcio_tcn' => $nut['calcio_tcn'] ?? 0.0,
                            'hierro_tcn' => $nut['hierro_tcn'] ?? 0.0,
                            'vit_a_tcn' => $nut['vit_a_tcn'] ?? 0.0,
                            'vit_c_tcn' => $nut['vit_c_tcn'] ?? 0.0,
                            'vit_d_tcn' => $nut['vit_d_tcn'] ?? 0.0,
                            'est_tcn' => TablaComposicionNutricional::ESTADO_VIGENTE,
                        ]
                    );
                }
            }

            // Normalizar y traducir alimentos existentes que vinieron en inglés desde USDA
            $normalizer = new FoodNameNormalizerService();
            $existentesUsda = Alimento::where('src_ali', Alimento::FUENTE_USDA)->get();
            foreach ($existentesUsda as $ali) {
                $nombreLimpio = $normalizer->nombreAmigable($ali->nom_ext_ali ?: $ali->nom_ali);
                if ($nombreLimpio !== '' && $nombreLimpio !== $ali->nom_ali) {
                    $ali->update([
                        'nom_ali' => $nombreLimpio,
                        'idi_ali' => 'es',
                    ]);
                }
            }
        });
    }

